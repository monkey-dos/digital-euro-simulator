#!/usr/bin/env python3
"""Start the reference apps locally, without Docker (ADR 0007):

    DESP   http://127.0.0.1:8000
    PSP A  http://127.0.0.1:8001
    PSP B  http://127.0.0.1:8002

Each app runs as its own process and prints one line per message it sends or
receives. Waits until all of them answer GET /health. Ctrl+C stops all of them.

    python3 tools/run_local.py                  # apps talk to each other directly
    python3 tools/run_local.py --control-room   # all traffic through the relay;
                                                # control room at http://127.0.0.1:8100

With --control-room the network relay starts as well, and the apps are told to
call each other through it (only their addresses change, not their code). The
apps' waiting times are raised to one hour, so a message the game master holds
on pause does not run into a timeout.
"""
import argparse
import json
import os
import signal
import subprocess
import sys
import time
import urllib.error
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APPS = [
    # (name, folder, arguments, port)
    ("DESP", "apps/desp", ["app.py"], 8000),
    ("PSP A", "apps/psp", ["app.py", "config/psp-a.json"], 8001),
    ("PSP B", "apps/psp", ["app.py", "config/psp-b.json"], 8002),
]
RELAY = ("Relay", "apps/network-relay", ["relay.py"], 8100)
RELAY_URL = "http://127.0.0.1:8100"
LONG_WAIT = "3600"  # seconds; see --control-room above
_relay_env: dict = {}  # filled by use_relay(); empty = apps talk directly


def use_relay(mode: str = "play", delay: str = "1.5") -> None:
    """Route all app-to-app traffic through the relay (call before start_all)."""
    if RELAY not in APPS:
        APPS.append(RELAY)
    register = os.path.join(_tmp_dir(), "participants-via-relay.json")
    with open(os.path.join(ROOT, "apps", "desp", "config", "participants.json"), encoding="utf-8") as f:
        participants = json.load(f)
    slugs = {"SIMADEF0XXX": "psp-a", "SIMBDEF0XXX": "psp-b"}
    for bic, p in participants["participants"].items():
        p["pspApiUrl"] = f"{RELAY_URL}/r/desp/{slugs[bic]}"
    participants["_note"] = "Generated by tools/run_local.py --control-room: the DESP reaches the banks through the relay."
    with open(register, "w", encoding="utf-8") as f:
        json.dump(participants, f, indent=2)
    _relay_env.update({
        "DESP": {"DESP_PARTICIPANTS": register, "DESP_FORWARD_TIMEOUT": LONG_WAIT},
        "PSP A": {"DESP_URL": f"{RELAY_URL}/r/psp-a/desp", "PSP_HTTP_TIMEOUT": LONG_WAIT, "PSP_STATUS_TIMEOUT": LONG_WAIT},
        "PSP B": {"DESP_URL": f"{RELAY_URL}/r/psp-b/desp", "PSP_HTTP_TIMEOUT": LONG_WAIT, "PSP_STATUS_TIMEOUT": LONG_WAIT},
        "Relay": {"RELAY_MODE": mode, "RELAY_DELAY": delay},
    })


def _tmp_dir() -> str:
    import tempfile
    d = os.path.join(tempfile.gettempdir(), "digital-euro-simulator")
    os.makedirs(d, exist_ok=True)
    return d


def healthy(port: int) -> bool:
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/health", timeout=0.5) as r:
            return r.status == 200
    except (urllib.error.URLError, OSError):
        return False


def start_all(log_dir: str | None = None, timeout: float = 20.0) -> list:
    """Start all apps. With log_dir, each app's output goes to <log_dir>/<name>.log,
    otherwise to this terminal. Returns the processes; raises SystemExit on failure."""
    busy = [f"{name} (port {port})" for name, _, _, port in APPS if healthy(port)]
    if busy:
        raise SystemExit(f"Already running: {', '.join(busy)}. Stop them first, or run without --start.")
    procs = [_spawn(name, log_dir) for name, _, _, _ in APPS]
    wait_healthy(procs, log_dir, timeout)
    return procs


def _spawn(name: str, log_dir: str | None):
    _, folder, args, port = next(a for a in APPS if a[0] == name)
    out = open(os.path.join(log_dir, name.replace(" ", "-") + ".log"), "a") if log_dir else None
    env = dict(os.environ, PYTHONUNBUFFERED="1", **_relay_env.get(name, {}))
    p = subprocess.Popen([sys.executable, *args], cwd=os.path.join(ROOT, folder), stdout=out,
                         stderr=subprocess.STDOUT if out else None, env=env, start_new_session=True)
    p.sim_name, p.sim_port = name, port
    return p


def restart(procs: list, name: str, log_dir: str | None = None, timeout: float = 20.0) -> None:
    """Start one app again (after stop_all([that one])); replaces it in `procs`."""
    i = next(i for i, p in enumerate(procs) if p.sim_name == name)
    procs[i] = _spawn(name, log_dir)
    wait_healthy([procs[i]], log_dir, timeout)


def wait_healthy(procs: list, log_dir: str | None, timeout: float) -> None:
    deadline = time.time() + timeout
    waiting = list(procs)
    while waiting and time.time() < deadline:
        for p in list(waiting):
            if p.poll() is not None:
                stop_all(procs)
                where = f" See {os.path.join(log_dir, p.sim_name.replace(' ', '-') + '.log')}." if log_dir else ""
                raise SystemExit(f"{p.sim_name} stopped right after start (exit code {p.returncode}).{where}")
            if healthy(p.sim_port):
                waiting.remove(p)
        time.sleep(0.1)
    if waiting:
        stop_all(procs)
        raise SystemExit("Not healthy in time: " + ", ".join(p.sim_name for p in waiting))


def stop_all(procs: list) -> None:
    for p in procs:
        if p.poll() is None:
            try:
                os.killpg(p.pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
    for p in procs:
        try:
            p.wait(timeout=5)
        except subprocess.TimeoutExpired:
            os.killpg(p.pid, signal.SIGKILL)


def _stop_on_sigterm(signum, frame):
    raise KeyboardInterrupt  # handled like Ctrl+C below


def main():
    ap = argparse.ArgumentParser(description="Start the simulator apps locally.")
    ap.add_argument("--control-room", action="store_true",
                    help="also start the network relay and send all traffic through it (control room on port 8100)")
    ap.add_argument("--pause", action="store_true", help="with --control-room: start paused (step by step)")
    args = ap.parse_args()
    signal.signal(signal.SIGTERM, _stop_on_sigterm)
    signal.signal(signal.SIGINT, signal.default_int_handler)  # Ctrl+C, also when started in the background
    if args.control_room:
        use_relay("pause" if args.pause else "play")
    procs = start_all()
    print("\nAll apps are up:", ", ".join(f"{p.sim_name} http://127.0.0.1:{p.sim_port}" for p in procs))
    if args.control_room:
        print(f"\n  Control room:  {RELAY_URL}/   (open it in your browser)\n", flush=True)
        print("Stop: Ctrl+C\n", flush=True)
    else:
        print("Try:  python3 tools/e2e_flows.py      Stop: Ctrl+C\n", flush=True)
    try:
        while all(p.poll() is None for p in procs):
            time.sleep(0.5)
        print("An app stopped; stopping the others.")
    except KeyboardInterrupt:
        print("\nStopping …")
    finally:
        stop_all(procs)


if __name__ == "__main__":
    main()
