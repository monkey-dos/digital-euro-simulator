#!/usr/bin/env python3
"""Bundle the example sequences for the observer.

Writes
  apps/observer/scenarios.js      – data file loaded by apps/observer/index.html
  apps/observer/dist/observer.html – single self-contained file (data inlined),
                                     e.g. for publishing or e-mailing
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EX = os.path.join(ROOT, "examples")
OBS = os.path.join(ROOT, "apps", "observer")

ORDER = ["p2p-same-psp", "p2p-two-psps", "funding-same-psp", "defunding-same-psp",
         "p2p-reverse-waterfall-same-psp", "p2p-waterfall-two-psps"]


def read_readme(folder):
    lines = open(os.path.join(folder, "README.md"), encoding="utf-8").read().split("\n")
    title = lines[0].lstrip("# ").strip()
    summary = next((l for l in lines[1:] if l.strip() and not l.startswith("|")), "")
    return title, summary.strip()


def main():
    test_data = json.load(open(os.path.join(EX, "test-data.json"), encoding="utf-8"))
    folders = sorted(d for d in os.listdir(EX) if os.path.isdir(os.path.join(EX, d)))
    folders = [f for f in ORDER if f in folders] + [f for f in folders if f not in ORDER]
    scenarios = []
    for name in folders:
        d = os.path.join(EX, name)
        title, summary = read_readme(d)
        steps = [json.load(open(f, encoding="utf-8")) for f in sorted(glob.glob(os.path.join(d, "[0-9][0-9]-*.json")))]
        scenarios.append({"id": name, "title": title, "summary": summary, "steps": steps})
    data = {"testData": test_data, "scenarios": scenarios}
    js = "/* generated by tools/build_observer.py – do not edit */\nwindow.OBSERVER_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
    with open(os.path.join(OBS, "scenarios.js"), "w", encoding="utf-8") as f:
        f.write(js)
    html = open(os.path.join(OBS, "index.html"), encoding="utf-8").read()
    tag = '<script src="scenarios.js"></script>'
    assert tag in html
    os.makedirs(os.path.join(OBS, "dist"), exist_ok=True)
    with open(os.path.join(OBS, "dist", "observer.html"), "w", encoding="utf-8") as f:
        f.write(html.replace(tag, "<script>\n" + js.replace("</", "<\\/") + "</script>"))
    print(f"{len(scenarios)} scenarios, {sum(len(s['steps']) for s in scenarios)} steps bundled")


if __name__ == "__main__":
    main()
